const { execSync } = require('child_process');
const http = require('http');

async function ensureCdpRunning() {
  return new Promise((resolve) => {
    const req = http.get('http://127.0.0.1:9222/json/version', (res) => {
      resolve(true);
    });
    req.on('error', () => {
      console.log('[!] CDP port 9222 not active. Auto-launching Chrome CDP...');
      try {
        const isWin = process.platform === 'win32';
        const scriptPath = path.resolve(__dirname, 'scripts', isWin ? 'test-cdp.ps1' : 'test-cdp.sh');
        if (isWin) {
          execSync(`powershell -ExecutionPolicy Bypass -File "${scriptPath}"`, { stdio: 'inherit' });
        } else {
          execSync(`bash "${scriptPath}"`, { stdio: 'inherit' });
        }
      } catch (e) {
        console.error('[-] Failed to auto-launch Chrome CDP script:', e.message);
      }
      resolve(false);
    });
    req.end();
  });
}

async function runClaudeReview(options = {}) {
  const {
    diffFilePath = 'pr_review_prompt.txt',
    gptResponseFilePath = 'gpt_review_response.txt',
    outputFile = 'claude_review_response.txt',
    forceNewChat = true
  } = options;

  const resolvedDiffPath = path.resolve(diffFilePath);
  const resolvedGptPath = gptResponseFilePath ? path.resolve(gptResponseFilePath) : null;

  if (!fs.existsSync(resolvedDiffPath)) {
    throw new Error(`File not found -> ${resolvedDiffPath}`);
  }

  await ensureCdpRunning();

  let gptResponseText = options.gptResponseText || '';
  if (!gptResponseText && resolvedGptPath && fs.existsSync(resolvedGptPath)) {
    gptResponseText = fs.readFileSync(resolvedGptPath, 'utf-8');
  }

  const promptDiffText = fs.readFileSync(resolvedDiffPath, 'utf-8');

  const rawDiffPath = path.resolve('pr_raw_diff.txt');
  let fullDiffText = '';
  if (fs.existsSync(rawDiffPath)) {
    fullDiffText = fs.readFileSync(rawDiffPath, 'utf-8');
  }

  // Build combined 2nd-pass audit prompt
  let combinedPrompt = promptDiffText;
  if (gptResponseText) {
    combinedPrompt = `You are a Lead Software Architect conducting a final 2nd-pass Code Review (Verification & Consensus Gate).

Below is the Pull Request Review metadata, code diff, and first-pass review findings generated by ChatGPT Web.

==================================================
1. ORIGINAL PR METADATA & DIFF
==================================================
${promptDiffText}

FULL GIT DIFF:
${fullDiffText}

==================================================
2. CHATGPT FIRST-PASS REVIEW RESPONSE
==================================================
${gptResponseText}

==================================================
3. YOUR SECOND-PASS VERIFICATION & AUDIT INSTRUCTIONS
==================================================
As the Final Auditor and Senior Lead Architect, perform a 2nd-pass review:
1. Verify each finding reported by ChatGPT against the code diff and context (Evidence Gate).
2. Filter out false positives, hallucinated errors, or subjective nitpicks.
3. Identify any critical security, financial, logic, or state bugs that ChatGPT missed.
4. Output your FINAL VERDICT at the VERY BEGINNING of your response on its own line:

REVIEW_STATUS: APPROVED

or

REVIEW_STATUS: CHANGES_REQUESTED

If CHANGES_REQUESTED, output the verified/final findings using EXACTLY:

[FINDING]
Severity: CRITICAL|HIGH|MEDIUM|LOW
File: path/to/file
Problem: <specific problem>
Evidence: <concrete execution path / call sequence>
Failure scenario: <realistic failure scenario>
Recommended fix: <practical code snippet or implementation approach>
[/FINDING]

After all findings, provide a concise summary explaining your verdict.
`;
  }

  console.log('[1] Connecting to Chrome CDP (Claude.ai)...');
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9222');
  
  const contexts = browser.contexts();
  const allPages = contexts.flatMap(c => c.pages());
  let claudePage = allPages.find(p => p.url().includes('claude.ai'));

  if (forceNewChat || !claudePage) {
    console.log('[2] Navigating to https://claude.ai/new for a clean chat session...');
    if (!claudePage) {
      const context = contexts[0] || await browser.newContext();
      claudePage = await context.newPage();
    }
    await claudePage.goto('https://claude.ai/new', { waitUntil: 'domcontentloaded' });
    await claudePage.waitForTimeout(4000);
  } else {
    console.log('[2] Reusing existing Claude chat session...');
  }

  await claudePage.bringToFront();

  console.log('[3] Finding Claude prompt input element...');
  
  // Try candidate selectors for Claude input
  const candidateSelectors = [
    'div[contenteditable="true"]',
    '.ProseMirror',
    'fieldset div[contenteditable="true"]',
    'div[aria-label*="Write"]',
    'div[aria-label*="Claude"]',
    'textarea'
  ];

  let inputSelector = null;
  for (const sel of candidateSelectors) {
    if (await claudePage.locator(sel).count() > 0 && await claudePage.locator(sel).first().isVisible()) {
      inputSelector = sel;
      break;
    }
  }

  if (!inputSelector) {
    console.log('[-] Waiting for contenteditable selector on Claude...');
    await claudePage.waitForSelector('div[contenteditable="true"], .ProseMirror', { state: 'visible', timeout: 15000 });
    inputSelector = 'div[contenteditable="true"], .ProseMirror';
  }

  console.log(`[4] Typing prompt into Claude (${inputSelector})...`);
  const inputEl = claudePage.locator(inputSelector).first();
  await inputEl.click();

  await claudePage.evaluate(([sel, text]) => {
    const el = document.querySelector(sel);
    if (!el) return;
    el.focus();
    if (el.isContentEditable) {
      document.execCommand('insertText', false, text);
    } else {
      el.value = text;
    }
    el.dispatchEvent(new Event('input', { bubbles: true }));
    el.dispatchEvent(new Event('change', { bubbles: true }));
  }, [inputSelector, combinedPrompt]);

  await claudePage.waitForTimeout(1500);

  // Find send button
  console.log('[5] Clicking Send button on Claude...');
  const sendSelectors = [
    'button[aria-label*="Send"]',
    'button[aria-label*="send"]',
    'fieldset button:has(svg)',
    'button:has(svg[aria-label*="Send"])'
  ];

  let sent = false;
  for (const sSel of sendSelectors) {
    const btn = claudePage.locator(sSel).last();
    if (await btn.count() > 0 && await btn.isVisible()) {
      await btn.click();
      sent = true;
      break;
    }
  }

  if (!sent) {
    console.log('[+] Send button not directly found, pressing Enter...');
    await claudePage.keyboard.press('Enter');
  }

  console.log('[6] Waiting for Claude response streaming to complete & text to stabilize...');
  
  await claudePage.waitForTimeout(5000);

  // Helper to extract current assistant response
  const extractClaudeText = async () => {
    const responseSelectors = [
      '.font-claude-message',
      'div[data-is-streaming]',
      'div.grid',
      '.prose'
    ];

    for (const rSel of responseSelectors) {
      const msgs = claudePage.locator(rSel);
      const count = await msgs.count();
      if (count > 0) {
        const text = await msgs.nth(count - 1).innerText();
        if (text && text.trim().length > 20) {
          return text;
        }
      }
    }
    return await claudePage.evaluate(() => document.body.innerText);
  };

  // Poll until Stop button is gone and text has REVIEW_STATUS or text length stabilizes
  let lastText = '';
  let stableCount = 0;
  let pollAttempts = 0;
  const maxPolls = 30;

  while (pollAttempts < maxPolls) {
    const stopBtn = claudePage.locator('button[aria-label*="Stop"], button:has-text("Stop response")');
    const isStreaming = await stopBtn.count() > 0 && await stopBtn.first().isVisible();
    
    const currentText = await extractClaudeText();
    const hasStatus = /^REVIEW_STATUS:\s*(APPROVED|CHANGES_REQUESTED)/im.test(currentText);

    if (currentText && currentText === lastText && currentText.length > 50) {
      stableCount++;
    } else {
      stableCount = 0;
    }
    lastText = currentText;

    if (!isStreaming && (hasStatus || stableCount >= 2)) {
      console.log(`[+] Response complete and verified (Attempt ${pollAttempts + 1}, HasStatus: ${hasStatus}).`);
      break;
    }

    await claudePage.waitForTimeout(3000);
    pollAttempts++;
  }

  console.log('[7] Reading final Claude response...');
  const resultText = await extractClaudeText();

  console.log('\n--- CLAUDE RESPONSE ---\n' + resultText + '\n-----------------------\n');

  if (outputFile) {
    const resolvedOutputPath = path.resolve(outputFile);
    fs.writeFileSync(resolvedOutputPath, resultText, 'utf-8');
    console.log(`[+] Saved Claude Response to: ${resolvedOutputPath}`);
  }

  const match = resultText.match(/^REVIEW_STATUS:\s*(APPROVED|CHANGES_REQUESTED)\s*$/im);
  const status = match ? match[1].toUpperCase() : 'UNKNOWN';

  return {
    status,
    resultText,
    browser
  };
}

module.exports = { runClaudeReview };

// Standalone execution
if (require.main === module) {
  (async () => {
    try {
      const args = process.argv.slice(2);
      const diffFilePath = args.find(a => !a.startsWith('--')) || 'pr_review_prompt.txt';
      const gptResponseFilePath = 'gpt_review_response.txt';

      const result = await runClaudeReview({ diffFilePath, gptResponseFilePath });
      console.log(`\n📌 Parsed Claude Final Status: ${result.status}`);

      if (result.status === 'APPROVED') {
        console.log('✅ Claude Code Review Verdict: APPROVED!');
        process.exit(0);
      } else {
        console.log('❌ Claude Code Review Verdict: CHANGES_REQUESTED (or UNKNOWN)!');
        process.exit(1);
      }
    } catch (err) {
      console.error('ERROR in test-claude-pr:', err);
      process.exit(1);
    }
  })();
}
